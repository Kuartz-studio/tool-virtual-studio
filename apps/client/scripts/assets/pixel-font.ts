// Deux signes que l'ASCII n'a pas : le point médian et le signe fois (pour « 2 × 3 cases »).
const EXTRA_COLUMNS: Record<string, readonly [number, number, number, number, number]> = {
  '·': [0x00, 0x00, 0x08, 0x00, 0x00],
  '×': [0x00, 0x14, 0x08, 0x14, 0x00],
};

// Les accents, en points (colonne, rangée) sur deux rangées : l'aigu, le grave, le circonflexe et le tréma ; la cédille n'a qu'un crochet dessous.
const ACCENTS: Record<string, ReadonlyArray<readonly [number, number]>> = {
  '́': [[3, 0], [2, 1]],
  '̀': [[1, 0], [2, 1]],
  '̂': [[2, 0], [1, 1], [3, 1]],
  '̈': [[1, 1], [3, 1]],
};
const CEDILLA = '̧';

// La boîte d'une ligne : TOP rangées libres au-dessus des majuscules (l'accent d'une majuscule), BODY rangées de lettre (une majuscule en prend 7,
// une minuscule 5, les 2 du haut restant libres pour son accent), BELOW rangées dessous (la queue d'un g, la cédille).
const TOP = 2;
const BODY = 7;
const BELOW = 3;
export const TEXT_ROWS = TOP + BODY + BELOW;
const ADVANCE = 6;
const SPACE_ADVANCE = 4;

// La largeur d'un texte, en pixels, à cette échelle (chaque point devient un carré de `scale` pixels).
export function textWidth(text: string, scale = 1): number {
  let width = 0;
  for (const char of text.normalize('NFC')) width += (char === ' ' ? SPACE_ADVANCE : ADVANCE) * scale;
  return Math.max(0, width - scale);
}

// Les colonnes d'un caractère de base, ou celles du point d'interrogation pour ce que la police ne connaît pas.
function columnsOf(char: string): readonly number[] {
  const extra = EXTRA_COLUMNS[char];
  if (extra) return extra;
  const code = char.charCodeAt(0);
  return ASCII_COLUMNS[code >= 0x20 && code <= 0x7e ? code - 0x20 : '?'.charCodeAt(0) - 0x20]!;
}

function drawDot(img: Img, x: number, y: number, color: Rgba, scale: number): void {
  img.fillRect(x, y, scale, scale, color);
}

// Un caractère, son coin haut-gauche en (x, y) : la lettre de base, puis son accent s'il en a un.
function drawChar(img: Img, x: number, y: number, char: string, color: Rgba, scale: number): void {
  const [base = ' ', ...marks] = [...char.normalize('NFD')];
  const columns = columnsOf(base);
  const accent = marks.find((mark) => ACCENTS[mark]);
  columns.forEach((bits, column) => {
    // Le point du i cède la place à l'accent.
    const kept = accent && base === 'i' && column === 2 ? bits & ~0x01 : bits;
    for (let row = 0; row < 8; row++) {
      if (kept & (1 << row)) drawDot(img, x + column * scale, y + (TOP + row) * scale, color, scale);
    }
  });
  if (accent) {
    const top = base >= 'A' && base <= 'Z' ? 0 : TOP;
    for (const [column, row] of ACCENTS[accent]!) drawDot(img, x + column * scale, y + (top + row) * scale, color, scale);
  }
  if (marks.includes(CEDILLA)) {
    drawDot(img, x + 2 * scale, y + (TOP + 7) * scale, color, scale);
    drawDot(img, x + 1 * scale, y + (TOP + 8) * scale, color, scale);
  }
}

// Écrit `text` sur une ligne, son coin haut-gauche en (x, y). Renvoie la largeur écrite.
export function drawText(img: Img, x: number, y: number, text: string, color: Rgba, scale = 1): number {
  let cursor = x;
  for (const char of text.normalize('NFC')) {
    if (char !== ' ') drawChar(img, cursor, y, char, color, scale);
    cursor += (char === ' ' ? SPACE_ADVANCE : ADVANCE) * scale;
  }
  return cursor - x - scale;
}

// Coupe `text` en lignes qui tiennent dans `maxWidth` pixels, aux espaces ; un mot plus long que la ligne reste entier sur la sienne.
export function wrapText(text: string, maxWidth: number, scale = 1): string[] {
  const lines: string[] = [];
  let line = '';
  for (const word of text.split(' ')) {
    const candidate = line === '' ? word : `${line} ${word}`;
    if (line !== '' && textWidth(candidate, scale) > maxWidth) {
      lines.push(line);
      line = word;
    } else {
      line = candidate;
    }
  }
  if (line !== '') lines.push(line);
  return lines;
}
